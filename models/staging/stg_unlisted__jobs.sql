-- One row per job per extract the job changed in. Renamed and typed; nothing else.
select
    id                                   as job_id,
    extract_date,
    company_id,
    ats,
    external_id,
    trim(title)                          as title,
    nullif(trim(department), '')         as department,
    nullif(trim(team), '')               as team,
    nullif(employment_type, '')          as employment_type,
    nullif(trim(location_raw), '')       as location_raw,
    nullif(country, '')                  as country,
    nullif(region, '')                   as region,
    remote                               as is_remote,
    nullif(remote_scope, '')             as remote_scope,
    nullif(open_to, '')                  as open_to,
    comp_min,
    comp_max,
    nullif(comp_currency, '')            as comp_currency,
    nullif(comp_period, '')              as comp_period,
    exp_min_years,
    exp_max_years,
    posted_at,
    first_seen_at,
    last_seen_at,
    closed_at,
    updated_at,
    content_hash
from {{ source('unlisted', 'jobs') }}
